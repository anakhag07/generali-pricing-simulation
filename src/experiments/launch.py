"""Shared local/Slurm launch orchestration for experiment entry points."""

from __future__ import annotations

import argparse
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from datetime import datetime
import json
import os
from pathlib import Path
import re
import subprocess
from types import SimpleNamespace
from typing import Any, Literal

from experiments.paths import results_root
from experiments.slurm import (
    SlurmArraySpec,
    SlurmSubmissionError,
    assert_jax_gpu_available,
    in_slurm_allocation,
    submit_to_slurm_if_needed,
)

LaunchMode = Literal["auto", "local", "slurm"]
TaskPayload = Mapping[str, Any] | None
TaskRunner = Callable[[int, "LaunchContext"], TaskPayload]
RunAll = Callable[["LaunchContext"], None]
Collector = Callable[["LaunchContext"], None]


@dataclass(frozen=True)
class LaunchPlan:
    """Task-level launch plan for one experiment entry point."""

    name: str
    task_count: int
    requires_jax: bool
    run_task: TaskRunner
    run_all: RunAll | None = None
    collect: Collector | None = None
    runs_root: str | None = None
    default_launch: LaunchMode = "auto"
    default_array: bool = False


@dataclass(frozen=True)
class LaunchContext:
    """Resolved launch state passed to task runners and collectors."""

    plan_name: str
    runs_root: Path
    sweep_id: str
    sweep_dir: Path
    tasks_dir: Path
    launch_mode: LaunchMode
    array: bool
    task_index: int | None = None

    def task_record_path(self, task_index: int) -> Path:
        """Return the JSON task-record path for ``task_index``."""
        return self.tasks_dir / f"task_{task_index:03d}.json"


def add_launch_args(
    parser: argparse.ArgumentParser,
    *,
    default_launch: LaunchMode | None = None,
    default_array: bool | None = None,
) -> None:
    """Add common local/Slurm launch arguments to an entry-point parser."""
    parser.add_argument(
        "--launch",
        choices=("auto", "local", "slurm"),
        default=default_launch,
        help=(
            "How to launch the entry point: auto submits to Slurm when outside "
            "an allocation, local runs in the current process, and slurm always "
            "submits when outside an allocation."
        ),
    )
    parser.add_argument(
        "--no-sbatch",
        action="store_true",
        help="Compatibility alias for --launch local.",
    )
    array_group = parser.add_mutually_exclusive_group()
    array_group.add_argument(
        "--array",
        dest="array",
        action="store_true",
        default=default_array,
        help="Submit task-level Slurm arrays when using --launch auto/slurm.",
    )
    array_group.add_argument(
        "--no-array",
        dest="array",
        action="store_false",
        help="Run all tasks serially in one local process or one Slurm job.",
    )
    parser.add_argument(
        "--array-max-parallel",
        type=int,
        default=None,
        help="Optional Slurm array concurrency cap, passed as %%N in --array.",
    )
    parser.add_argument(
        "--task-index",
        type=int,
        default=None,
        help="Run a single task locally for debugging.",
    )
    parser.add_argument(
        "--sweep-id",
        default=None,
        help="Stable id for shared array/collector outputs; generated by default.",
    )
    parser.add_argument(
        "--collect",
        action="store_true",
        help=argparse.SUPPRESS,
    )


def run_launch_plan(
    plan: LaunchPlan,
    *,
    args: argparse.Namespace,
    argv: Sequence[str],
    cwd: Path | None = None,
    env: Mapping[str, str] | None = None,
    runner: Any = subprocess.run,
) -> None:
    """Execute or submit ``plan`` according to parsed launch arguments."""
    _validate_plan(plan)
    env_map = os.environ if env is None else env
    workdir = (Path.cwd() if cwd is None else Path(cwd)).resolve()
    launch_mode = _resolve_launch_mode(plan, args, env_map)
    array_requested = _resolve_array_requested(plan, args)
    sweep_id = str(getattr(args, "sweep_id", None) or _new_sweep_id())
    context = _launch_context(
        plan,
        launch_mode=launch_mode,
        array=array_requested,
        sweep_id=sweep_id,
        task_index=None,
    )

    if launch_mode == "slurm" and not in_slurm_allocation(env_map):
        try:
            _submit_parent_jobs(
                plan,
                args=args,
                argv=argv,
                cwd=workdir,
                runner=runner,
                array_requested=array_requested,
                sweep_id=sweep_id,
            )
        except SlurmSubmissionError as exc:
            raise SystemExit(str(exc)) from None
        return

    if bool(getattr(args, "collect", False)):
        _run_collector(plan, context)
        return

    _assert_jax_if_needed(plan)

    task_index = _selected_task_index(args, env_map, array_requested=array_requested)
    if task_index is not None:
        task_context = _launch_context(
            plan,
            launch_mode=launch_mode,
            array=array_requested,
            sweep_id=sweep_id,
            task_index=task_index,
        )
        _run_one_task(plan, task_index, task_context)
        return

    if plan.run_all is not None and not array_requested:
        plan.run_all(context)
        return

    for index in range(plan.task_count):
        task_context = _launch_context(
            plan,
            launch_mode=launch_mode,
            array=array_requested,
            sweep_id=sweep_id,
            task_index=index,
        )
        _run_one_task(plan, index, task_context)
    if plan.collect is not None:
        _run_collector(plan, context)


def read_task_records(context: LaunchContext) -> list[dict[str, Any]]:
    """Read all task record JSON files written under ``context.tasks_dir``."""
    records: list[dict[str, Any]] = []
    if not context.tasks_dir.exists():
        return records
    for path in sorted(context.tasks_dir.glob("task_*.json")):
        with path.open("r", encoding="utf-8") as handle:
            records.append(json.load(handle))
    return records


def task_payloads(context: LaunchContext, *, require_success: bool = True) -> list[dict[str, Any]]:
    """Return task payloads from task records, optionally requiring success."""
    payloads: list[dict[str, Any]] = []
    failures: list[str] = []
    for record in read_task_records(context):
        if record.get("status") != "success":
            failures.append(f"task {record.get('task_index')}: {record.get('error', 'failed')}")
            continue
        payload = record.get("payload") or {}
        if isinstance(payload, dict):
            payloads.append(payload)
    if require_success and failures:
        raise RuntimeError("Cannot collect failed task records: " + "; ".join(failures))
    return payloads


def _submit_parent_jobs(
    plan: LaunchPlan,
    *,
    args: argparse.Namespace,
    argv: Sequence[str],
    cwd: Path,
    runner: Any,
    array_requested: bool,
    sweep_id: str,
) -> None:
    child_argv = _argv_with_value(argv, "--sweep-id", sweep_id)
    if array_requested:
        child_argv = _argv_with_flag(child_argv, "--array")
    array_spec = (
        SlurmArraySpec(0, plan.task_count - 1, getattr(args, "array_max_parallel", None))
        if array_requested
        else None
    )
    submission = submit_to_slurm_if_needed(
        requires_jax=plan.requires_jax,
        no_sbatch=False,
        argv=child_argv,
        cwd=cwd,
        runner=runner,
        array=array_spec,
    )
    if submission is None:
        return
    job_kind = "array" if array_requested else "job"
    print(
        f"Submitted {submission.profile.name} Slurm {job_kind} {submission.job_id}; "
        f"logs: {submission.profile.output}"
    )
    if array_requested and plan.collect is not None:
        collector_argv = _argv_with_flag(child_argv, "--collect")
        collector = submit_to_slurm_if_needed(
            requires_jax=False,
            no_sbatch=False,
            argv=collector_argv,
            cwd=cwd,
            runner=runner,
            dependency=f"afterany:{submission.job_id}",
        )
        if collector is not None:
            print(
                f"Submitted collector Slurm job {collector.job_id} after {submission.job_id}; "
                f"logs: {collector.profile.output}"
            )


def _run_one_task(plan: LaunchPlan, task_index: int, context: LaunchContext) -> None:
    _validate_task_index(plan, task_index)
    try:
        payload = plan.run_task(task_index, context) or {}
    except BaseException as exc:
        _write_task_record(
            context,
            task_index,
            {
                "task_index": task_index,
                "status": "failed",
                "error": f"{type(exc).__name__}: {exc}",
                "finished_at": datetime.now().isoformat(timespec="seconds"),
            },
        )
        raise
    _write_task_record(
        context,
        task_index,
        {
            "task_index": task_index,
            "status": "success",
            "payload": dict(payload),
            "finished_at": datetime.now().isoformat(timespec="seconds"),
        },
    )


def _run_collector(plan: LaunchPlan, context: LaunchContext) -> None:
    if plan.collect is None:
        raise ValueError(f"Launch plan {plan.name!r} has no collector.")
    plan.collect(context)


def _write_task_record(context: LaunchContext, task_index: int, payload: Mapping[str, Any]) -> None:
    context.tasks_dir.mkdir(parents=True, exist_ok=True)
    with context.task_record_path(task_index).open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, indent=2, sort_keys=True, ensure_ascii=True, default=_json_default)


def _launch_context(
    plan: LaunchPlan,
    *,
    launch_mode: LaunchMode,
    array: bool,
    sweep_id: str,
    task_index: int | None,
) -> LaunchContext:
    runs_root = results_root() if plan.runs_root is None else Path(plan.runs_root)
    sweep_dir = runs_root / _path_part(plan.name) / "sweeps" / _path_part(sweep_id)
    return LaunchContext(
        plan_name=plan.name,
        runs_root=runs_root,
        sweep_id=sweep_id,
        sweep_dir=sweep_dir,
        tasks_dir=sweep_dir / "tasks",
        launch_mode=launch_mode,
        array=array,
        task_index=task_index,
    )


def _resolve_launch_mode(
    plan: LaunchPlan,
    args: argparse.Namespace,
    env: Mapping[str, str],
) -> LaunchMode:
    if bool(getattr(args, "no_sbatch", False)):
        return "local"
    requested = getattr(args, "launch", None) or plan.default_launch
    if requested == "auto":
        return "local" if in_slurm_allocation(env) else "slurm"
    return requested


def _resolve_array_requested(plan: LaunchPlan, args: argparse.Namespace) -> bool:
    requested = getattr(args, "array", None)
    array = plan.default_array if requested is None else bool(requested)
    return bool(array and plan.task_count > 1)


def _selected_task_index(
    args: argparse.Namespace,
    env: Mapping[str, str],
    *,
    array_requested: bool,
) -> int | None:
    explicit = getattr(args, "task_index", None)
    if explicit is not None:
        return int(explicit)
    if array_requested and env.get("SLURM_ARRAY_TASK_ID") is not None:
        return int(str(env["SLURM_ARRAY_TASK_ID"]))
    return None


def _assert_jax_if_needed(plan: LaunchPlan) -> None:
    if not plan.requires_jax:
        return
    status = assert_jax_gpu_available([SimpleNamespace(compute_backend="jax")])
    if status is not None:
        print(status)


def _validate_plan(plan: LaunchPlan) -> None:
    if plan.task_count <= 0:
        raise ValueError("LaunchPlan.task_count must be positive.")


def _validate_task_index(plan: LaunchPlan, task_index: int) -> None:
    if task_index < 0 or task_index >= plan.task_count:
        raise IndexError(
            f"Task index {task_index} out of range for {plan.task_count} tasks."
        )


def _argv_with_flag(argv: Sequence[str], flag: str) -> list[str]:
    out = list(argv)
    if flag not in out:
        out.append(flag)
    return out


def _argv_with_value(argv: Sequence[str], option: str, value: str) -> list[str]:
    out = list(argv)
    if option in out or any(item.startswith(f"{option}=") for item in out):
        return out
    out.extend([option, value])
    return out


def _new_sweep_id() -> str:
    return datetime.now().strftime("%Y%m%d_%H%M%S")


def _path_part(value: object) -> str:
    text = str(value).strip().replace(" ", "-").replace("/", "-")
    return re.sub(r"[^A-Za-z0-9_.-]+", "-", text) or "run"


def _json_default(value: object) -> object:
    if isinstance(value, Path):
        return str(value)
    if hasattr(value, "item"):
        try:
            return value.item()  # type: ignore[no-any-return,union-attr]
        except Exception:  # noqa: BLE001 - fallback must never mask task status writes.
            pass
    if hasattr(value, "tolist"):
        try:
            return value.tolist()  # type: ignore[no-any-return,union-attr]
        except Exception:  # noqa: BLE001
            pass
    return str(value)


